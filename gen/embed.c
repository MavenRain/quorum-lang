/* Writes a C file that holds the bytes of a source file as SYMBOL_source
   and SYMBOL_source_len. SYMBOL is domain when it is not given.
   Usage: tcc -run gen/embed.c domain/domain.lang build/domain.c
          tcc -run gen/embed.c lib/prelude.lang build/prelude.c prelude
   SHARED by the tcc kits. */
#include <stdio.h>

static int embed(const char *name, const char *symbol, FILE *in, FILE *out) {
  fprintf(out, "/* Generated by gen/embed.c from %s. Do not edit. */\n", name);
  fprintf(out, "#include <stddef.h>\n\nconst unsigned char %s_source[] = {", symbol);
  size_t count = 0;
  int c = fgetc(in);
  while (c != EOF) {
    fprintf(out, "%s0x%02x,", count % 12 == 0 ? "\n  " : " ", (unsigned)c);
    count++;
    c = fgetc(in);
  }
  fprintf(out, "\n  0x00\n};\nconst size_t %s_source_len = %lu;\n", symbol, (unsigned long)count);
  return ferror(in) == 0 && ferror(out) == 0;
}

int main(int argc, char **argv) {
  if (argc != 3 && argc != 4) {
    fputs("usage: embed IN OUT [SYMBOL]\n", stderr);
    return 2;
  }
  FILE *in = fopen(argv[1], "rb");
  FILE *out = in == NULL ? NULL : fopen(argv[2], "wb");
  int ok = out != NULL && embed(argv[1], argc == 4 ? argv[3] : "domain", in, out);
  if (in != NULL) fclose(in);
  if (out != NULL) ok = fclose(out) == 0 && ok;
  if (!ok) fprintf(stderr, "embed: cannot copy %s to %s\n", argv[1], argv[2]);
  return ok ? 0 : 2;
}
